// Generates packages/zouriel_ui/lib/src/fx/sea_shapes.g.dart from the Angular library's shared sea
// shapes (projects/ui/fx/assets/maldives/*.svg), so both libraries draw the same silhouettes.
//
//   node tool/gen_sea_shapes.mjs <angular>/projects/ui/fx/assets/maldives packages/zouriel_ui/lib/src/fx/sea_shapes.g.dart
//
// The SVGs use absolute M, C, L and Z commands only (the Angular spec checks this); anything else fails here.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dir, outFile] = process.argv.slice(2);
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const num = (v) => (Number.isInteger(v) ? v.toFixed(1) : String(v));

function commands(d) {
  const out = [];
  for (const m of d.matchAll(/([A-Za-z])([^A-Za-z]*)/g)) {
    const v = m[2].trim() ? m[2].trim().split(/[\s,]+/).map(Number) : [];
    const op = { M: 0, L: 1, C: 2, Z: 3 }[m[1]];
    const arity = { M: 2, L: 2, C: 6, Z: 0 }[m[1]];
    if (op === undefined) throw new Error(`unsupported path command ${m[1]} in ${d.slice(0, 40)}`);
    if (arity === 0 ? v.length : v.length % arity || !v.length) throw new Error(`bad arguments for ${m[1]}: ${m[2]}`);
    if (arity === 0) out.push(op);
    for (let i = 0; i < v.length; i += arity) out.push(op, ...v.slice(i, i + arity));
  }
  return out;
}

const files = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort();
const shapes = files.map((f) => {
  const svg = readFileSync(join(dir, f), 'utf8');
  const [, , w, h] = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const parts = [...svg.matchAll(/<path ([^>]*)\/>/g)].map((m) => {
    const a = Object.fromEntries([...m[1].matchAll(/([\w-]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
    return { tone: a['data-tone'], stroke: a['stroke-width'] ? +a['stroke-width'] : null, opacity: a.opacity ? +a.opacity : null, ops: commands(a.d) };
  });
  return { name: camel(f.replace('.svg', '')), w, h, parts };
});

const out = `// GENERATED by tool/gen_sea_shapes.mjs from the @zouriel/ui (Angular) sea shapes
// (projects/ui/fx/assets/maldives/*.svg). Do not edit by hand; re-run the generator after changing them.
// ignore_for_file: lines_longer_than_80_chars

part of 'sea_shapes.dart';

${shapes.map((s) => `/// \`${s.name}\`, from the shared SVG source.
const UiSeaShape _${s.name} = UiSeaShape(
  size: Size(${num(s.w)}, ${num(s.h)}),
  parts: [
${s.parts.map((p) => `    UiSeaShapePart(
      tone: UiSeaTone.${p.tone},${p.stroke !== null ? `\n      stroke: ${num(p.stroke)},` : ''}${p.opacity !== null ? `\n      opacity: ${num(p.opacity)},` : ''}
      ops: [${p.ops.map(num).join(', ')}],
    ),`).join('\n')}
  ],
);`).join('\n\n')}
`;
writeFileSync(outFile, out);
console.log(`${shapes.length} shapes -> ${outFile}`);
