#!/usr/bin/env python3
"""Writes lib/src/form_builder/engine/slug_table.g.dart: the NFKD fold table fbSlug uses.

Dart has no Unicode normalisation, so fbSlug looks characters up here instead of calling
`normalize('NFKD')` like the web version. Run from the repo root: python3 tool/gen_slug_table.py
"""
import unicodedata
from pathlib import Path

entries = []
for cp in range(0x80, 0x30000):
    c = chr(cp)
    d = unicodedata.normalize('NFKD', c)
    d = ''.join(x for x in d if not (0x300 <= ord(x) <= 0x36F))
    if d != c and any(ch.isascii() and ch.isalnum() for ch in d):
        entries.append((cp, ''.join(ch if (ch.isascii() and ch.isalnum()) else '_' for ch in d)))

lines, cur = [], ''
for cp, v in entries:
    item = f"0x{cp:X}: '{v}', "
    if len(cur) + len(item) > 110:
        lines.append(cur.rstrip())
        cur = ''
    cur += item
lines.append(cur.rstrip())
body = '\n'.join('  ' + l for l in lines)
Path('packages/zouriel_ui/lib/src/form_builder/engine/slug_table.g.dart').write_text(f"""// GENERATED by tool/gen_slug_table.py from Python's unicodedata ({unicodedata.unidata_version}). Do not edit.
//
// For fbSlug: what each character becomes after NFKD normalisation with combining marks
// (U+0300-U+036F) removed, as the web version does with `normalize('NFKD')`. Only characters
// whose result contains an ASCII letter or digit are listed; other ASCII is written as `_` (the
// slug turns it into `_` anyway). Characters not listed are kept as they are.

const Map<int, String> fbSlugFold = {{
{body}
}};
""")
print(len(entries), 'entries')
