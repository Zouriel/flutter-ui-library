#!/usr/bin/env node
/*
 * Generates the country list used by the phone input (`ui-phone-input` / `UiPhoneInput`): ISO 3166
 * alpha-2 code, English name, dial code, national trunk prefix, whether the country is the main one
 * for a shared dial code, and the leading digits that pick it out of a shared code.
 *
 * Source: libphonenumber's PhoneNumberMetadata.xml (dial codes, `mainCountryForCode`, `nationalPrefix`,
 * `leadingDigits`), pinned to a release tag; English names from CLDR through Node's
 * Intl.DisplayNames. Non-geographic entities (id "001") are left out. The same script lives in both
 * libraries (Angular: tools/gen-phone-countries.mjs, Flutter: tool/gen_phone_countries.mjs) so both
 * get the same data.
 *
 *   node tools/gen-phone-countries.mjs --format ts   --out projects/ui/form/src/phone-countries.ts
 *   node tool/gen_phone_countries.mjs  --format dart --out packages/zouriel_ui/lib/src/forms/text/phone_countries.dart
 *
 * Options: --tag v9.0.42 (libphonenumber release), --xml <local copy of PhoneNumberMetadata.xml>.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const tag = arg('tag', 'v9.0.42');
const format = arg('format', 'ts');
const out = arg('out');
if (!out || !['ts', 'dart'].includes(format)) {
  console.error('usage: --format ts|dart --out <file> [--tag vX.Y.Z] [--xml file]');
  process.exit(2);
}
const url = `https://raw.githubusercontent.com/google/libphonenumber/${tag}/resources/PhoneNumberMetadata.xml`;
const xml = arg('xml') ? readFileSync(arg('xml'), 'utf8') : await (await fetch(url, { headers: { 'User-Agent': 'zouriel-ui-gen' } })).text();

const names = new Intl.DisplayNames(['en'], { type: 'region' });
const rows = [];
for (const m of xml.matchAll(/<territory\s([^>]*)>/g)) {
  const attrs = Object.fromEntries([...m[1].matchAll(/(\w+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
  const iso2 = attrs.id;
  if (!/^[A-Z]{2}$/.test(iso2)) continue; // "001": non-geographic entities
  const dial = attrs.countryCode;
  const name = names.of(iso2);
  if (!dial || !name || name === iso2) throw new Error(`no dial code or name for ${iso2}`);
  rows.push({
    iso2,
    name,
    dial,
    trunk: attrs.nationalPrefix ?? '',
    main: attrs.mainCountryForCode === 'true',
    leading: (attrs.leadingDigits ?? '').replace(/\s+/g, ''),
  });
}
// Every shared dial code names exactly one main country (libphonenumber's mainCountryForCode, or the
// only country with that code).
const byDial = Map.groupBy(rows, (r) => r.dial);
for (const [dial, list] of byDial) {
  if (list.length === 1) list[0].main = true;
  const mains = list.filter((r) => r.main).length;
  if (mains !== 1) throw new Error(`+${dial}: ${mains} main countries`);
}
rows.sort((a, b) => a.name.localeCompare(b.name, 'en'));
if (rows.length < 240) throw new Error(`only ${rows.length} countries`);

const header = [
  `GENERATED by gen-phone-countries.mjs from libphonenumber ${tag} PhoneNumberMetadata.xml`,
  `(${url})`,
  `and CLDR English names (Node ${process.version}, ICU ${process.versions.icu}). Do not edit by hand.`,
  `${rows.length} countries. Row: [ISO 3166 alpha-2, English name, dial code, trunk prefix, main for its dial code, leading digits].`,
];
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$');
let text;
if (format === 'ts') {
  text = `/*\n${header.map((l) => ` * ${l}`).join('\n')}\n */\n\n` +
    `/** [iso2, name, dial, trunk, main, leadingDigits] */\n` +
    `export const UI_PHONE_COUNTRY_ROWS: readonly (readonly [string, string, string, string, boolean, string])[] = [\n` +
    rows.map((r) => `  ['${r.iso2}', '${esc(r.name)}', '${r.dial}', '${esc(r.trunk)}', ${r.main}, '${esc(r.leading)}'],`).join('\n') +
    `\n];\n`;
} else {
  text = `${header.map((l) => `// ${l}`).join('\n')}\n\n` +
    `/// [iso2, name, dial, trunk, main, leadingDigits]\n` +
    `const List<(String, String, String, String, bool, String)> uiPhoneCountryRows = [\n` +
    rows.map((r) => `  ('${r.iso2}', '${esc(r.name)}', '${r.dial}', '${esc(r.trunk)}', ${r.main}, r'${r.leading.replace(/'/g, '')}'),`).join('\n') +
    `\n];\n`;
}
writeFileSync(out, text);
console.log(`wrote ${rows.length} countries to ${out}`);
